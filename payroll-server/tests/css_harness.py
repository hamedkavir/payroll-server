#!/usr/bin/env python3
"""
css_harness.py — computed-style diff harness for the CSS refactor (PLAN.md item 17).

    python3 tests/css_harness.py snap  <outdir> [--mock] [config...]   # take a snapshot of the current client/
    python3 tests/css_harness.py diff  <dirA> <dirB>     # compare two snapshots; exit 1 on any diff
    python3 tests/css_harness.py imp                     # list !important rules with specificity <= (0,1,0)

Snapshot = for every config (light/dark x RTL/LTR x desktop/mobile = 8, + light/dark RTL 1366x768 compact = 10) and every page (<section class="page">):
  the full computed style (+ ::before/::after) and the rounded bounding box of every VISIBLE element
  (the active page + the shell). Offline mode: the API is never contacted; pages are shown with showPage().
  --mock (v117): the API is answered in the page by tests/mock_api.js, the app "connects", and every page is snapshotted
  with data; the person-workspace pages (loan form, advance, goods, mehr, …) once per tab with a selected person, plus the
  personnel profile. This covers the markup generated by the JS templates. Compare --mock snapshots only with --mock ones.
"""
import sys, os, json, hashlib, itertools, threading, http.server, socketserver, functools

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIENT = os.path.join(ROOT, "client")

CONFIGS = [
    dict(name=f"{theme}-{d}-{vp}", dark=(theme == "dark"), dir=d,
         vp=dict(width=1280, height=900) if vp == "desktop" else dict(width=390, height=800))
    for theme, d, vp in itertools.product(["light", "dark"], ["rtl", "ltr"], ["desktop", "mobile"])
] + [
    # v119: 1366×768 laptop screens. The 1280×900 desktop config never matches the compact media queries of theme.css
    # [14]–[16] (max-height ≤ 800/820px), so without these two configs the compact layers were unverified.
    dict(name=f"{theme}-rtl-compact", dark=(theme == "dark"), dir="rtl", vp=dict(width=1366, height=768))
    for theme in ["light", "dark"]
]

JS_SNAPSHOT = r"""
() => {
  const out = {};
  // custom properties (--*) are excluded: their enumeration order is unstable and new tokens must not count as a diff; their effect shows up in the real properties
  const props = Array.from(getComputedStyle(document.documentElement)).filter(p => !p.startsWith('--')).sort();
  const vis = el => {
    const cs = getComputedStyle(el);
    if (cs.display === 'none' || cs.visibility === 'hidden') return false;
    for (let p = el.parentElement; p; p = p.parentElement) if (getComputedStyle(p).display === 'none') return false;
    return true;
  };
  const sig = (cs) => props.map(p => p + ':' + cs.getPropertyValue(p)).join(';').split(location.origin).join('');   // random port must not leak into the signature
  const pathOf = el => {
    const parts = [];
    for (let e = el; e && e.nodeType === 1 && e !== document.documentElement; e = e.parentElement) {
      let i = 1; for (let s = e.previousElementSibling; s; s = s.previousElementSibling) if (s.tagName === e.tagName) i++;
      parts.unshift(e.tagName.toLowerCase() + (e.id ? '#' + e.id : '') + ':' + i);
    }
    return parts.join('>');
  };
  const els = [document.documentElement, ...document.body.querySelectorAll('*')];
  for (const el of els) {
    if (['SCRIPT', 'STYLE', 'LINK', 'META', 'TITLE', 'HEAD'].includes(el.tagName)) continue;
    if (!vis(el)) continue;
    const cs = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    const rec = { s: sig(cs), b: [Math.round(r.x), Math.round(r.y), Math.round(r.width), Math.round(r.height)] };
    for (const ps of ['::before', '::after']) {
      const pc = getComputedStyle(el, ps);
      if (pc.content && pc.content !== 'none' && pc.content !== 'normal') rec[ps] = sig(pc);
    }
    out[pathOf(el)] = rec;
  }
  return out;
}
"""

def h(x):
    return hashlib.sha1(json.dumps(x, sort_keys=True).encode()).hexdigest()[:12]

class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
    def end_headers(self):
        self.send_header("Cache-Control", "no-store"); super().end_headers()

def serve():
    handler = functools.partial(Quiet, directory=CLIENT)
    srv = socketserver.TCPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, srv.server_address[1]

SETTLE = """() => new Promise(res => { let last = -1, same = 0;
    const t = setInterval(() => { const n = document.body.innerHTML.length;
      same = n === last ? same + 1 : 0; last = n; if (same >= 4) { clearInterval(t); res(); } }, 50); })"""

# views of one page in --mock mode: [(name, js-to-run)]
MOCK_VIEWS = """(name) => {
  const v = [[name, "showPage('" + name + "')"]];
  if (typeof PAGE_TABS !== 'undefined' && PAGE_TABS[name]) {
    const K = ["form","rep","rec","stat","chg"];
    PAGE_TABS[name].forEach((_, i) => v.push([name + ":" + K[i],
      "app.wk.code='1001';setWkTab('" + name + "','" + K[i] + "');showPage('" + name + "');renderWk('" + name + "')"]));
  }
  if (name === 'personnel') v.push(['personnel:profile', "showPage('personnel');loadProfile('1001')"]);
  return v;
}"""

def snap(outdir, detail=False, mock=False):
    from playwright.sync_api import sync_playwright
    os.makedirs(outdir, exist_ok=True)
    srv, port = serve()
    total = 0
    with sync_playwright() as pw:
        b = pw.chromium.launch()
        for cfg in CONFIGS:
            ctx = b.new_context(viewport=cfg["vp"], reduced_motion="reduce", locale="fa-IR")
            ctx.add_init_script(
                "try{localStorage.setItem('psAppearance'," + json.dumps(json.dumps({"dark": cfg["dark"]})) + ");"
                "localStorage.removeItem('psApiBase')}catch(e){}")
            if mock:
                ctx.add_init_script(path=os.path.join(os.path.dirname(os.path.abspath(__file__)), "mock_api.js"))
            pg = ctx.new_page()
            pg.route("**/api/**", lambda r: r.abort())
            pg.goto(f"http://127.0.0.1:{port}/payslip-online.html", wait_until="load")
            pg.wait_for_timeout(400)
            if mock:   # connect to the mocked API, then stop the background sync so the DOM can settle
                pg.evaluate("document.getElementById('btnConnect').click()")
                pg.wait_for_timeout(600); pg.evaluate(SETTLE); pg.evaluate("stopSync()")
            pg.evaluate(f"document.documentElement.dir = '{cfg['dir']}'")
            pg.add_style_tag(content="*,*::before,*::after{animation:none!important;transition:none!important;caret-color:transparent!important}")
            pg.evaluate("document.getElementById('loginWrap') && (document.getElementById('loginWrap').hidden = true)")
            pages = pg.evaluate("[...document.querySelectorAll('section.page')].map(s=>s.id.replace(/^page-/,''))")
            res = {}
            views = [v for name in pages for v in (pg.evaluate(MOCK_VIEWS, name) if mock else [[name, f"showPage('{name}')"]])]
            for name, js in views:
                pg.evaluate("document.querySelectorAll('.modalWrap').forEach(m=>m.remove())") if mock else None
                pg.evaluate(js)
                # async renders (aborted API calls -> error text) must settle: wait until the DOM stops changing
                pg.evaluate(SETTLE)
                data = pg.evaluate(JS_SNAPSHOT)
                res[name] = {k: ({"h": h(v), "full": v} if detail else {"h": h(v)}) for k, v in data.items()}
                total += len(data)
            with open(os.path.join(outdir, cfg["name"] + ".json"), "w") as f:
                json.dump(res, f)
            print(f"  {cfg['name']:<22} {len(res)} views, {sum(len(v) for v in res.values())} elements", flush=True)
            ctx.close()
        b.close()
    srv.shutdown()
    print(f"snapshot done: {total} element records -> {outdir}")

# !important declarations whose selector specificity is <= (0,1,0). Only these can make a `:where(.u-x){p:v!important}`
# utility (or a plain .u-x !important one) cascade differently from the inline style it replaced: an inline style loses to
# every !important rule, a utility only to !important rules that are more specific (or equally specific and later).
IMP_JS = r"""
() => {
  const spec = sel => {
    let a=0,b=0,c=0; let s = sel;
    // functional pseudos
    s = s.replace(/:where\((?:[^()]|\([^()]*\))*\)/g, '');
    const fn = /:(is|not|has)\(((?:[^()]|\([^()]*\))*)\)/;
    let m;
    while ((m = fn.exec(s))) {
      const parts = m[2].split(',').map(x => spec(x.trim()));
      parts.sort((x,y)=> (y[0]-x[0])||(y[1]-x[1])||(y[2]-x[2]));
      a+=parts[0][0]; b+=parts[0][1]; c+=parts[0][2];
      s = s.slice(0,m.index) + s.slice(m.index+m[0].length);
    }
    s = s.replace(/"[^"]*"|'[^']*'/g,'');
    a += (s.match(/#[\w-]+/g)||[]).length;
    b += (s.match(/\.[\w-]+/g)||[]).length + (s.match(/\[[^\]]*\]/g)||[]).length;
    s = s.replace(/\[[^\]]*\]/g,'');
    const pe = (s.match(/::[\w-]+/g)||[]).length; s = s.replace(/::[\w-]+(\([^)]*\))?/g,'');
    b += (s.match(/:[\w-]+(\([^)]*\))?/g)||[]).length; s = s.replace(/:[\w-]+(\([^)]*\))?/g,'');
    s = s.replace(/#[\w-]+|\.[\w-]+/g,' ');
    c += pe + (s.match(/(^|[\s>+~(])([a-zA-Z][\w-]*)/g)||[]).length;
    return [a,b,c];
  };
  const out = [];
  const walk = (rules, sheet, media) => {
    for (const r of rules) {
      if (r.cssRules && !(r instanceof CSSStyleRule)) { walk(r.cssRules, sheet, media + (r.conditionText ? ' @' + r.conditionText : (r.media? ' @'+r.media.mediaText:''))); continue; }
      if (!(r instanceof CSSStyleRule)) continue;
      const props = [...r.style].filter(p => r.style.getPropertyPriority(p) === 'important');
      if (!props.length) continue;
      for (const sel of r.selectorText.split(/,(?![^(]*\))/)) {
        const sp = spec(sel.trim());
        if (sp[0] === 0 && sp[1] <= 1) out.push({sheet, media, sel: sel.trim(), sp, props});
      }
    }
  };
  for (const ss of document.styleSheets) {
    const name = ss.href ? ss.href.split('/').pop() : (ss.ownerNode && ss.ownerNode.id || 'inline-style');
    try { walk(ss.cssRules, name, ''); } catch (e) {}
  }
  return out;
}
"""

def imp():
    from playwright.sync_api import sync_playwright
    srv, port = serve()
    with sync_playwright() as pw:
        b = pw.chromium.launch(); pg = b.new_page()
        pg.route("**/api/**", lambda r: r.abort())
        pg.goto(f"http://127.0.0.1:{port}/payslip-online.html", wait_until="load")
        res = pg.evaluate(IMP_JS); b.close()
    srv.shutdown()
    for x in res:
        if x["sel"].startswith(":where(.u-"): continue   # the utilities themselves
        print(f"{x['sheet']:<20} {x['sp']} {x['media'][:30]:<30} {x['sel'][:60]:<60} {','.join(x['props'])[:120]}")

def diff(a, b):
    bad = 0; checked = 0
    for cfg in CONFIGS:
        fa, fb = (os.path.join(d, cfg["name"] + ".json") for d in (a, b))
        if not os.path.exists(fa) and not os.path.exists(fb):   # e.g. snapshots taken before the v119 compact configs
            print(f"SKIP {cfg['name']} (in neither snapshot)"); continue
        A, B = json.load(open(fa)), json.load(open(fb))
        for page in sorted(set(A) | set(B)):
            pa, pb = A.get(page, {}), B.get(page, {})
            for k in sorted(set(pa) | set(pb)):
                checked += 1
                if pa.get(k, {}).get("h") != pb.get(k, {}).get("h"):
                    bad += 1
                    if bad <= 40: print(f"DIFF {cfg['name']} / {page} / {k}")
    print(f"{checked} element records compared across {len(CONFIGS)} configs: {bad} diffs")
    return 1 if bad else 0

if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "snap":
        rest = [a for a in sys.argv[3:] if a != "--mock"]
        if rest:   # optional: only the configs whose name contains one of the given substrings
            CONFIGS[:] = [c for c in CONFIGS if any(x in c["name"] for x in rest)]
        snap(sys.argv[2], mock="--mock" in sys.argv[3:])
    elif cmd == "imp": imp()
    elif cmd == "diff": sys.exit(diff(sys.argv[2], sys.argv[3]))
    else: sys.exit(__doc__)
